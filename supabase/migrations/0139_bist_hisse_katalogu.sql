-- ── 4) Tetikleyici (0076 edge_function_url + cron_headers deseni) ──────────
-- Ayrı secret açılmadı: 0129 emsali (kamu verisi okuyan cron, TÜFE çekimiyle
-- aynı secret). Yeni secret yasin'in iki sunucuda elle girmesini beklerdi.
create or replace function public.trigger_bist_hisse_katalog()
returns void
language plpgsql
security definer
set search_path = public, vault, net
as $$
begin
  perform net.http_post(
    url := public.edge_function_url('bist-hisse-katalog'),
    headers := public.cron_headers('inflation_fetch_cron_secret'),
    body := jsonb_build_object('source', 'cron'),
    -- İki TradingView + bir KAP isteği (30 sn zaman aşımı) + upsert.
    timeout_milliseconds := 90000
  );
end;
$$;

revoke all on function public.trigger_bist_hisse_katalog() from public, anon, authenticated;

-- Her gün TR 07:40 (04:40 UTC): seans öncesi; halka arzın ilk işlem günü
-- sabahı listede olur. Hafta sonu da koşar (ucuz; kod değişikliği hafta
-- sonu duyurulabiliyor).
select cron.unschedule(jobid) from cron.job where jobname = 'bist-hisse-katalog';
select cron.schedule('bist-hisse-katalog', '40 4 * * *',
  $$select public.trigger_bist_hisse_katalog()$$);

-- İki sunucu birebir; tek bilinçli fark cron `active` (0119 kuralı).
do $$
begin
  if exists (select 1 from cron.job where jobname <> 'bist-hisse-katalog')
     and not exists (select 1 from cron.job where jobname <> 'bist-hisse-katalog' and active) then
    perform cron.alter_job(job_id := jobid, active := false)
       from cron.job where jobname = 'bist-hisse-katalog';
    raise notice '0139: projede tum cron isleri kapali — bist-hisse-katalog da kapali kuruldu.';
  end if;
end $$;

-- ── 5) Doğrulama ────────────────────────────────────────────────────────────
do $$
begin
  if not has_table_privilege('authenticated', 'public.bist_hisse', 'select') then
    raise exception '0139: authenticated SELECT grant eksik';
  end if;
  if has_table_privilege('authenticated', 'public.bist_hisse', 'insert')
     or has_table_privilege('authenticated', 'public.bist_hisse', 'update')
     or has_table_privilege('authenticated', 'public.bist_hisse', 'delete') then
    raise exception '0139: authenticated yazma yetkisi verilmemeli';
  end if;
  if has_table_privilege('anon', 'public.bist_hisse', 'select') then
    raise exception '0139: anon erisimi olmamali';
  end if;
  if not exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public' and c.relname = 'bist_hisse'
         and c.relrowsecurity and c.relforcerowsecurity) then
    raise exception '0139: RLS/FORCE RLS acik degil';
  end if;
  if has_function_privilege('authenticated', 'public.trigger_bist_hisse_katalog()', 'EXECUTE')
     or has_function_privilege('anon', 'public.trigger_bist_hisse_katalog()', 'EXECUTE') then
    raise exception '0139: trigger_bist_hisse_katalog istemciden cagrilabilir olmamali';
  end if;
  if not exists (select 1 from cron.job where jobname = 'bist-hisse-katalog') then
    raise exception '0139: bist-hisse-katalog cron isi kurulmadi';
  end if;
  if (select count(*) from public.bist_hisse where aktif) < 450 then
    raise exception '0139: seed eksik';
  end if;
  raise notice '0139 tamam: BIST hisse katalogu, seed ve cron kuruldu.';
end $$;
