-- gören tüm hisseler olmalı." Hisse listesi uygulamaya gömülüydü; elle
-- tutulduğu için eskidi (BIST 100'ün 24'ü, KUTPO gibi yüzlerce hisse yoktu)
-- ve her halka arz yeni bir sürüm bekliyordu. Liste artık burada:
-- `bist-hisse-katalog` fonksiyonu her sabah borsadan (TradingView evreni +
-- KAP unvanları) tazeler, istemci okur ve cihazda saklar. Sunucuya
-- ulaşamayan istemci gömülü listeye (`lib/models/bist_hisseleri.dart`) düşer.
--
-- ## Kural
-- * Yeni kod eklenir; var olan satırın ADI ezilmez (seed'deki elle
--   düzeltilmiş adlar korunur).
-- * Görülmeyen kod silinmez, `aktif = false` olur (kod değişti / borsadan
--   çıktı). Fiyat bu tablodan GELMEZ; fiyat kaynağı sözleşmesi değişmez.
--
-- ## Eski istemciler
-- Yalnız EKLER: bir tablo, bir tetikleyici, bir cron işi. Eski build
-- tabloyu hiç okumaz, gömülü listesiyle çalışmaya devam eder.
--
-- ## Dağıtım sırası
-- Bu migration (iki sunucu) → `bist-hisse-katalog` fonksiyonu → ilk tur
-- elle: `select public.trigger_bist_hisse_katalog();` → kontrol:
-- `select count(*) filter (where aktif), count(*) filter (where xu100), max(guncellendi) from public.bist_hisse;`
-- Seed fonksiyon hiç koşmasa da tabloyu doldurur (628 hisse, 2026-10-10).

-- ── 1) Tablo ────────────────────────────────────────────────────────────────
create table if not exists public.bist_hisse (
  kod          text        primary key check (kod ~ '^[A-Z0-9]{3,6}$'),
  ad           text        not null check (length(ad) between 2 and 120),
  -- BIST 100 üyesi mi (bilgi; seçici bugün kullanmıyor).
  xu100        boolean     not null default false,
  -- Borsada bugün işlem görüyor mu. Düşen satır silinmez.
  aktif        boolean     not null default true,
  ilk_goruldu  timestamptz not null default now(),
  guncellendi  timestamptz not null default now()
);

